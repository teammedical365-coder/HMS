const START_CODE_B = 104;
const STOP_CODE = 106;

export function generateCode128Svg(text, options = {}) {
    const height = options.height || 45;
    const barWidth = options.barWidth || 1.8;
    const quietZone = options.quietZone || 8;

    const cleanText = String(text || '').trim();
    if (!cleanText) return '';

    const values = [START_CODE_B];
    let checkSum = START_CODE_B;

    for (let i = 0; i < cleanText.length; i++) {
        const code = cleanText.charCodeAt(i) - 32;
        if (code >= 0 && code <= 95) {
            values.push(code);
            checkSum += code * (i + 1);
        }
    }

    const checkValue = checkSum % 103;
    values.push(checkValue);
    values.push(STOP_CODE);

    let x = quietZone;
    let rects = [];

    for (let k = 0; k < values.length; k++) {
        const val = values[k];
        const pattern = CODE128_PATTERNS[val];
        if (!pattern) continue;

        for (let j = 0; j < pattern.length; j++) {
            const width = pattern[j] * barWidth;
            if (j % 2 === 0) {
                rects.push(`<rect x="${x.toFixed(1)}" y="0" width="${width.toFixed(1)}" height="${height}" fill="#000000" />`);
            }
            x += width;
        }
    }

    const totalWidth = Math.ceil(x + quietZone);

    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${totalWidth} ${height}" width="${totalWidth}" height="${height}" style="display:block;margin:0 auto;max-width:100%;">${rects.join('')}</svg>`;
}
