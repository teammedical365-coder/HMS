/**
 * Translates clinical question text or option string
 */
export function getTranslatedClinicalText(text, lang = 'en') {
    if (!text || lang === 'en') return text;
    const trimmed = text.trim();
    const item = CLINICAL_TEXT_DICTIONARY[trimmed];
    if (item && item[lang]) {
        return item[lang];
    }
    return text;
}
