/**
 * Localizes UI label key according to language
 */
export function getUIText(key, lang = 'en') {
    const currentLangDict = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS.en;
    if (currentLangDict && currentLangDict[key] !== undefined) {
        return currentLangDict[key];
    }
    return UI_TRANSLATIONS.en[key] || key;
}

/**
 * Translates department name for display
 */
export function getTranslatedDepartment(deptName, lang = 'en') {
    if (!deptName || lang === 'en') return deptName;
    const item = DEPARTMENT_TRANSLATIONS[deptName];
    if (item && item[lang]) {
        return item[lang];
    }
    return deptName;
}

