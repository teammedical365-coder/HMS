const START_CODE_B = 104;
const STOP_CODE = 106;

/**
 * Generate Code 128B barcode SVG string.
 * @param {string} text - text to encode (ASCII 32..126)
 * @param {object} options - { height: 50, barWidth: 2, quietZone: 10 }
 * @returns {string} SVG markup string
 */
function generateCode128Svg(text, options = {}) {
    const height = options.height || 50;
    const barWidth = options.barWidth || 2;
    const quietZone = options.quietZone || 10;

    const cleanText = String(text || '').trim();
    if (!cleanText) return '';

    // Values sequence starting with Start Code B
    const values = [START_CODE_B];
    let checkSum = START_CODE_B;

    for (let i = 0; i < cleanText.length; i++) {
        const code = cleanText.charCodeAt(i) - 32;
        if (code >= 0 && code <= 95) {
            values.push(code);
            checkSum += code * (i + 1);
        }
    }

    const checkValue = checkSum % 103;
    values.push(checkValue);
    values.push(STOP_CODE);

    // Build rectangles
    let x = quietZone;
    let rects = '';

    for (const val of values) {
        const pattern = CODE128_PATTERNS[val];
        if (!pattern) continue;

        for (let j = 0; j < pattern.length; j++) {
            const width = pattern[j] * barWidth;
            if (j % 2 === 0) {
                // Bar (black)
                rects += `<rect x="${x}" y="0" width="${width}" height="${height}" fill="#000000" />`;
            }
            x += width;
        }
    }

    const totalWidth = x + quietZone;

    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${totalWidth} ${height}" width="${totalWidth}" height="${height}" style="display:block;max-width:100%;">${rects}</svg>`;
}

module.exports = {
    generateCode128Svg
};
